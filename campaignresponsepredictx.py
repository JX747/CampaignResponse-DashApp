def update_data_store(retail_contents, retail_filename, response_contents, response_filename):
    retail_data = None
    response_data = None
    status_messages = []

    if retail_contents and retail_filename:
        retail_df = parse_contents(retail_contents, retail_filename)
        if isinstance(retail_df, pd.DataFrame):
            retail_data = retail_df.to_json(date_format="iso", orient="split")
            status_messages.append(html.P(f"Online Retail Sales Data: {retail_filename} loaded successfully."))
        else:
            status_messages.append(retail_df)

    if response_contents and response_filename:
        response_df = parse_contents(response_contents, response_filename)
        if isinstance(response_df, pd.DataFrame):
            response_data = response_df.to_json(date_format="iso", orient="split")
            status_messages.append(html.P(f"Campaign Response Data: {response_filename} loaded successfully."))
        else:
            status_messages.append(response_df)

    return retail_data, response_data, html.Div(status_messages)


