def update_data_store(retail_contents, retail_filename, response_contents, response_filename):
    retail_data = None
    response_data = None
    status_messages = []

    if retail_contents and retail_filename:
        retail_df = parse_contents(retail_contents, retail_filename)
        if isinstance(retail_df, pd.DataFrame):
            retail_data = retail_df.to_json(date_format="iso", orient="split")
            status_messages.append(html.P(f"Online Retail Sales Data: {retail_filename} loaded successfully."))
        else:
            status_messages.append(retail_df)

    if response_contents and response_filename:
        response_df = parse_contents(response_contents, response_filename)
        if isinstance(response_df, pd.DataFrame):
            response_data = response_df.to_json(date_format="iso", orient="split")
            status_messages.append(html.P(f"Campaign Response Data: {response_filename} loaded successfully."))
        else:
            status_messages.append(response_df)

    return retail_data, response_data, html.Div(status_messages)


import pickle as _pickle

@app.callback(
    [
        Output("masterdata-with-predictions", "data"),
        Output("feature-importance-chart", "figure"),
        Output("feature-importance-table-container", "children"),
        Output("dashboard-content-container", "style"),
    ],
    Input("process-button", "n_clicks"),
    State("retail-data-store", "data"),
    State("response-data-store", "data"),
    prevent_initial_call=True,
)
def process_and_store_data(n_clicks, retail_json, response_json):
    # Keep return types consistent: (cache_key_or_None, Figure, children_or_None, style_dict)
    default_hidden = (None, go.Figure(), None, {"display": "none"})
    if n_clicks is None or not retail_json or not response_json:
        return default_hidden

    try:
        # 1) Parse uploaded stores safely
        try:
            retail_df = pd.read_json(retail_json, orient="split")
        except Exception as e:
            msg = f"Error parsing retail data: {e}"
            print(msg); traceback.print_exc()
            return None, go.Figure(), html.Div(msg, style={"color": "red"}), {"display": "none"}

        try:
            response_df = pd.read_json(response_json, orient="split")
        except Exception as e:
            msg = f"Error parsing response data: {e}"
            print(msg); traceback.print_exc()
            return None, go.Figure(), html.Div(msg, style={"color": "red"}), {"display": "none"}

        # 2) Process data
        try:
            masterdata = process_customer_data(retail_df, response_df)
        except Exception as e:
            msg = f"Error during data processing: {e}"
            print(msg); traceback.print_exc()
            return None, go.Figure(), html.Div(msg, style={"color": "red"}), {"display": "none"}

        # 3) Ensure model is available (lazy load if needed)
        global xgb, feature_columns
        if xgb is None or feature_columns is None:
            if MODEL_PATH.exists():
                try:
                    with MODEL_PATH.open("rb") as f:
                        (xgb, feature_columns) = pickle.load(f)
                except Exception as e:
                    print(f"Error loading model at processing time: {e}")
                    traceback.print_exc()

        if xgb is None or feature_columns is None:
            return None, go.Figure(), html.Div(f"Model file not found or failed to load: {MODEL_PATH}", style={"color": "red"}), {"display": "none"}

        # 4) Validate feature columns
        missing = [c for c in feature_columns if c not in masterdata.columns]
        if missing:
            msg = f"Missing feature columns in processed data: {missing}"
            print(msg)
            return None, go.Figure(), html.Div(msg, style={"color": "red"}), {"display": "none"}

        # 5) Predict
        X_test = masterdata[feature_columns]
        masterdata["prediction_proba"] = xgb.predict_proba(X_test)[:, 1]

        # 6) Build UI objects (figure + table)
        feature_importance_df = pd.DataFrame({
            "Feature": feature_columns,
            "Importance": xgb.feature_importances_
        }).sort_values("Importance", ascending=False)
        feature_importance_chart = px.bar(feature_importance_df, x="Importance", y="Feature", orientation="h")
        feature_importance_chart.update_layout(yaxis={"categoryorder": "total ascending"})
        feature_importance_table = dbc.Table.from_dataframe(feature_importance_df, striped=True, bordered=True, hover=True)

        # cache the dataframe to speed slider updates — key derived from JSON payload
        masterdata_json = masterdata.to_json(date_format="iso", orient="split")
        cache_key = hashlib.sha256(masterdata_json.encode("utf-8")).hexdigest()
        try:
            cache.set(cache_key, _pickle.dumps(masterdata))
            print(f"Cached masterdata with key: {cache_key}")
        except Exception:
            # caching errors shouldn't break the app
            print("Warning: failed to set cache for masterdata")

        # IMPORTANT: return only the cache key to the browser to avoid transferring the large JSON payload
        return cache_key, feature_importance_chart, feature_importance_table, {"display": "block"}

    except Exception as e:
        # Final catch-all — always return the right shapes
        print("Unexpected error in process_and_store_data:", e)
        traceback.print_exc()
        return None, go.Figure(), html.Div(f"Unexpected error: {e}", style={"color": "red"}), {"display": "none"}


@app.callback(
    [
        Output("prediction-summary-total-customers", "children"),
        Output("prediction-summary-respondents", "children"),
        Output("prediction-summary-non-respondents", "children"),
        Output("prediction-summary-response-rate", "children"),
        Output("prediction-summary-auc-score", "children"),
        Output("pie-chart-graph", "figure"),
        Output("prediction-table-output", "children"),
    ],
    [
        Input("prediction-threshold-slider", "value"),
        Input("masterdata-with-predictions", "data"),
    ],
    prevent_initial_call=True,
)
def update_dashboard_display(threshold, masterdata_key_or_json):
    if masterdata_key_or_json is None:
        return (
            html.P("Total Customers: N/A"),
            html.P("Predicted Respondents: N/A"),
            html.P("Predicted Non-Respondents: N/A"),
            html.P("Predicted Response Rate: N/A"),
            html.P("AUC Score: N/A"),
            go.Figure(),
            html.Div("Upload data and click 'Process Data' to see predictions."),
        )

    masterdata = None
    # First treat the incoming value as a cache key (preferred, small)
    try:
        cached = None
        try:
            cached = cache.get(masterdata_key_or_json)
        except Exception:
            cached = None

        if cached:
            try:
                masterdata = _pickle.loads(cached)
            except Exception:
                masterdata = None

        # if cache miss, attempt to parse the value directly as JSON (backwards compatibility)
        if masterdata is None:
            try:
                masterdata = pd.read_json(masterdata_key_or_json, orient="split")
            except Exception:
                masterdata = None

    except Exception as e:
        print(f"Error retrieving masterdata from cache or JSON: {e}")
        masterdata = None

    if masterdata is None:
        return (
            html.P("Total Customers: N/A"),
            html.P("Predicted Respondents: N/A"),
            html.P("Predicted Non-Respondents: N/A"),
            html.P("Predicted Response Rate: N/A"),
            html.P("AUC Score: N/A (no data)"),
            go.Figure(),
            html.Div("No processed data available. Click 'Process Data' first."),
        )

    if "prediction_proba" not in masterdata.columns:
        return (
            html.P("Total Customers: N/A"),
            html.P("Predicted Respondents: N/A"),
            html.P("Predicted Non-Respondents: N/A"),
            html.P("Predicted Response Rate: N/A"),
            html.P("AUC Score: N/A (prediction_proba missing)"),
            go.Figure(),
            html.Div("prediction_proba column is missing in the processed data."),
        )

    masterdata["predicted_response"] = (masterdata["prediction_proba"] >= threshold).astype(int)

    response_counts = masterdata["predicted_response"].value_counts().reindex([0, 1], fill_value=0)
    respondents = int(response_counts.get(1, 0))
    non_respondents = int(response_counts.get(0, 0))
    total_customers = len(masterdata)
    response_rate = (respondents / total_customers) * 100 if total_customers > 0 else 0

    try:
        auc_val = roc_auc_score(masterdata["response"], masterdata["prediction_proba"])
        auc_text = f"AUC Score: {auc_val:.4f}"
    except Exception as e:
        auc_text = f"AUC Score: N/A ({str(e)})"

    pie_data = pd.DataFrame({
        "Category": ["Responded", "Not Responded"],
        "Count": [respondents, non_respondents]
    })
    pie_chart = px.pie(
        pie_data,
        names="Category",
        values="Count",
        title="Campaign Response Rate",
        color_discrete_map={"Responded": "green", "Not Responded": "red"},
    )

    prediction_table_data = masterdata[["CustomerID", "prediction_proba", "predicted_response"]].sort_values(by="prediction_proba", ascending=False)
    filtered_table_data = prediction_table_data[prediction_table_data["predicted_response"] == 1]

    if filtered_table_data.empty:
        prediction_table_display = html.Div(f"No customers predicted to respond at a threshold of {threshold}.")
    else:
        prediction_table_display = dbc.Table.from_dataframe(filtered_table_data.head(10), striped=True, bordered=True, hover=True, className="mt-3")

    return (
        f"Total Customers: {total_customers}",
        f"Predicted Respondents: {respondents}",
        f"Predicted Non-Respondents: {non_respondents}",
        f"Predicted Response Rate: {response_rate:.2f}%",
        auc_text,
        pie_chart,
        prediction_table_display,
    )


